const ExcelJS = require("exceljs");

const MIN_WIDTH = 8;
const MAX_WIDTH = 60;

function sheetName(text, used) {
  let name = String(text || "Sheet").replace(/[:\\/?*[\]]/g, "-").trim().slice(0, 31) || "Sheet";
  let candidate = name;
  let counter = 2;
  while (used.indexOf(candidate.toLowerCase()) !== -1) {
    const suffix = " (" + counter + ")";
    candidate = name.slice(0, 31 - suffix.length) + suffix;
    counter += 1;
  }
  used.push(candidate.toLowerCase());
  return candidate;
}

function cellValue(value) {
  if (value === null || value === undefined) return "";
  if (typeof value === "number") return Number.isFinite(value) ? value : "";
  return String(value);
}

// The lines printed above the table on every sheet: the store name, the report
// title, its subtitle, and who generated the file.
function headingLines(sheet, header) {
  const lines = [];
  if (header.storeName) {
    lines.push({ text: String(header.storeName), font: { bold: true, size: 14 } });
  }
  if (sheet.title) {
    lines.push({ text: String(sheet.title), font: { bold: true, size: 12 } });
  }
  if (sheet.subtitle) {
    lines.push({ text: String(sheet.subtitle), font: { italic: true, size: 10, color: { argb: "FF4D5661" } } });
  }
  if (header.generatedBy) {
    lines.push({ text: "Generated by: " + header.generatedBy, font: { italic: true, size: 10, color: { argb: "FF4D5661" } } });
  }
  return lines;
}

async function buildWorkbook(sheets, header) {
  const workbook = new ExcelJS.Workbook();
  workbook.created = new Date();
  const used = [];
  if (!header) header = {};

  for (let sheetIndex = 0; sheetIndex < sheets.length; sheetIndex++) {
    const sheet = sheets[sheetIndex];
    const headers = [];
    if (Array.isArray(sheet.headers)) {
      for (let i = 0; i < sheet.headers.length; i++) {
        headers.push(String(sheet.headers[i]));
      }
    }
    let rows = [];
    if (Array.isArray(sheet.rows)) {
      rows = sheet.rows;
    }
    let money = [];
    if (Array.isArray(sheet.money)) {
      money = sheet.money;
    }
    // Rows (by position) whose numbers are peso amounts, for a Figure/Value sheet
    let moneyRows = [];
    if (Array.isArray(sheet.moneyRows)) {
      moneyRows = sheet.moneyRows;
    }
    let columnCount = Math.max(headers.length, 1);
    for (let i = 0; i < rows.length; i++) {
      if (Array.isArray(rows[i]) && rows[i].length > columnCount) {
        columnCount = rows[i].length;
      }
    }

    const ws = workbook.addWorksheet(sheetName(sheet.name, used));

    // Heading lines first, then one empty row, then the column headers.
    const lines = headingLines(sheet, header);
    for (let i = 0; i < lines.length; i++) {
      ws.getCell(i + 1, 1).value = lines[i].text;
      ws.getCell(i + 1, 1).font = lines[i].font;
    }
    let headerRow = 1;
    if (lines.length > 0) headerRow = lines.length + 2;

    if (headers.length > 0) {
      const head = ws.getRow(headerRow);
      head.values = headers;
      head.font = { bold: true, color: { argb: "FFFFFFFF" } };
      head.alignment = { vertical: "middle" };
      head.height = 20;
      for (let column = 1; column <= headers.length; column += 1) {
        head.getCell(column).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF1B1F24" } };
      }
      ws.views = [{ state: "frozen", ySplit: headerRow }];
      ws.autoFilter = { from: { row: headerRow, column: 1 }, to: { row: headerRow, column: headers.length } };
    }

    const widths = new Array(columnCount).fill(MIN_WIDTH);
    for (let index = 0; index < headers.length; index++) {
      widths[index] = Math.max(widths[index], headers[index].length + 2);
    }

    for (let rowIndex = 0; rowIndex < rows.length; rowIndex++) {
      let cells = [];
      if (Array.isArray(rows[rowIndex])) {
        cells = rows[rowIndex];
      }
      const added = ws.getRow(headerRow + 1 + rowIndex);
      for (let index = 0; index < cells.length; index++) {
        const cell = added.getCell(index + 1);
        cell.value = cellValue(cells[index]);
        const isMoneyNumber = typeof cell.value === "number" &&
          (money.includes(index) || moneyRows.includes(rowIndex));
        if (isMoneyNumber) cell.numFmt = "#,##0.00";
        let shown = String(cell.value).length;
        if (isMoneyNumber) {
          shown = cell.value.toFixed(2).length + 3;
        }
        widths[index] = Math.max(widths[index], Math.min(shown + 2, MAX_WIDTH));
        if (String(cell.value).length > MAX_WIDTH) cell.alignment = { wrapText: true, vertical: "top" };
      }
    }

    // A bold Total row under the last row, with one empty row between so sorting
    // and filtering do not pull it into the data.
    if (money.length > 0 && rows.length > 0) {
      const totalRow = ws.getRow(headerRow + 2 + rows.length);
      if (!money.includes(0)) {
        totalRow.getCell(1).value = "Total";
      }
      for (let m = 0; m < money.length; m++) {
        const column = money[m];
        if (!Number.isInteger(column) || column < 0) continue;
        let sum = 0;
        for (let rowIndex = 0; rowIndex < rows.length; rowIndex++) {
          if (Array.isArray(rows[rowIndex]) && typeof rows[rowIndex][column] === "number" &&
              Number.isFinite(rows[rowIndex][column])) {
            sum += rows[rowIndex][column];
          }
        }
        sum = Math.round(sum * 100) / 100;
        const cell = totalRow.getCell(column + 1);
        cell.value = sum;
        cell.numFmt = "#,##0.00";
        if (column < widths.length) {
          widths[column] = Math.max(widths[column], Math.min(sum.toFixed(2).length + 5, MAX_WIDTH));
        }
      }
      totalRow.font = { bold: true };
    }

    // A bold label and peso amount under the last row, e.g. ["Total Sales", 2370]
    if (Array.isArray(sheet.totalLine) && sheet.totalLine.length === 2) {
      const line = ws.getRow(headerRow + 2 + rows.length);
      line.getCell(1).value = String(sheet.totalLine[0]);
      let amount = Math.round(Number(sheet.totalLine[1]) * 100) / 100;
      if (!Number.isFinite(amount)) amount = 0;
      line.getCell(2).value = amount;
      line.getCell(2).numFmt = "#,##0.00";
      line.font = { bold: true };
      widths[0] = Math.max(widths[0], String(sheet.totalLine[0]).length + 2);
      if (widths.length > 1) {
        widths[1] = Math.max(widths[1], Math.min(amount.toFixed(2).length + 5, MAX_WIDTH));
      }
    }

    for (let index = 0; index < widths.length; index++) {
      ws.getColumn(index + 1).width = widths[index];
    }
  }

  return workbook;
}

async function sendWorkbook(response, fileName, sheets, header) {
  const workbook = await buildWorkbook(sheets, header);
  const safe = String(fileName || "report").replace(/[^\w.-]+/g, "-").replace(/^-|-$/g, "") || "report";
  response.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
  response.setHeader("Content-Disposition", "attachment; filename=\"" + safe + ".xlsx\"");
  await workbook.xlsx.write(response);
  response.end();
}

module.exports = { buildWorkbook: buildWorkbook, sendWorkbook: sendWorkbook };
